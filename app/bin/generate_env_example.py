#!/usr/bin/env python3
"""Generate app/.env.example from the settings classes.

decisions/configuration.md keeps secrets and non-public values out of every
configuration file: they come only from the environment. Each such field is
declared with ``contracts.configuration.env_only``, whose metadata names where a
developer gets the value. This script writes one commented line per such
environment name, grouped by owning settings module:

    # SLACK__BOT_TOKEN=    [codespaces] Bot token (xoxb-) the app acts with.

The classes are the ones ``bin.check_settings_key_ownership.collect_env_claims``
finds; each is imported and its ``model_fields`` walked, into nested models (a
tenant entry) through ``env_nested_delimiter``. Every emitted name must be one the
ownership check claims, so the file never names a variable nothing reads; a
claimed name that is not env-only is omitted on purpose, because a configuration
file holds it.

Usage:
    python3 -m bin.generate_env_example           # write app/.env.example
    python3 -m bin.generate_env_example --check   # exit 1 when the committed file differs
"""

import argparse
import importlib
import sys
import types
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Union, get_args, get_origin

from pydantic import BaseModel
from pydantic.fields import FieldInfo
from pydantic_settings import BaseSettings

from bin.check_settings_key_ownership import APP_ROOT, collect_env_claims
from contracts.configuration import is_env_only

OUTPUT = APP_ROOT / ".env.example"
SOURCES = {
    "codespaces": "a Codespaces secret of the repository (the Codespace exports it; restart the Codespace after a change)",
    "devcontainer": "the devcontainer's compose file sets it",
    "local": "set it in app/.env yourself when you need it",
}
HEADER = [
    "# Generated by bin/generate_env_example.py (make env-example); do not edit by hand.",
    "#",
    "# Every environment name a developer may set that no configuration file holds: the",
    "# secrets and non-public values (decisions/configuration.md). Everything else lives in",
    "# app/config/*.toml. Copy a line to app/.env, uncomment it and set the value there.",
    "#",
    "# Where a value comes from:",
    *(f"#   [{source}] {text}" for source, text in SOURCES.items()),
]


@dataclass(frozen=True)
class EnvName:
    """One environment-only name, the module that owns it, and where a developer gets its value."""

    name: str
    module: str
    source: str
    description: str


class GenerationError(Exception):
    """A field's metadata or name breaks the generator's rules."""


def _env_only(field: FieldInfo) -> dict[str, Any] | None:
    extra = field.json_schema_extra
    return extra if is_env_only(field) and isinstance(extra, dict) else None


def _nested_model(annotation: Any) -> type[BaseModel] | None:
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation
    if get_origin(annotation) in (Union, types.UnionType):
        models = [arg for arg in get_args(annotation) if isinstance(arg, type) and issubclass(arg, BaseModel)]
        return models[0] if len(models) == 1 else None
    return None


def _walk(model: type[BaseModel], prefix: str, delimiter: str | None, module: str) -> list[EnvName]:
    names: list[EnvName] = []
    for field_name, field in model.model_fields.items():
        name = (field.alias or f"{prefix}{field_name}").upper()
        meta = _env_only(field)
        if meta is not None:
            source = str(meta.get("source"))
            if source not in SOURCES:
                raise GenerationError(f"{module}: {name} has source {source!r}; expected one of {sorted(SOURCES)}")
            if not field.description:
                raise GenerationError(f"{module}: {name} is env-only but has no description")
            names.append(EnvName(name=name, module=module, source=source, description=field.description))
        nested = _nested_model(field.annotation)
        if nested is not None and delimiter:
            names.extend(_walk(nested, f"{name}{delimiter}", delimiter, module))
    return names


def _resolve(owner: str) -> type:
    module_name, qualname = owner.split(":", 1)
    target: Any = importlib.import_module(module_name)
    for part in qualname.split("."):
        target = getattr(target, part)
    if not isinstance(target, type):
        raise GenerationError(f"{owner} is not a class")
    return target


def collect(root: Path = APP_ROOT) -> tuple[list[EnvName], list[str]]:
    """Return the env-only names, sorted by module, and the claimed names omitted because a file holds them."""
    claims, errors = collect_env_claims(root)
    if errors:
        raise GenerationError("; ".join(error.message for error in errors))
    claimed = {claim.key for claim in claims}
    entries: dict[str, EnvName] = {}
    for owner in sorted({claim.owner for claim in claims}):
        cls = _resolve(owner)
        if not (isinstance(cls, type) and issubclass(cls, BaseSettings)):
            continue
        config = cls.model_config
        delimiter = config.get("env_nested_delimiter")
        for entry in _walk(cls, str(config.get("env_prefix") or ""), delimiter, cls.__module__):
            if entry.name.lower() not in claimed:
                raise GenerationError(f"{owner}: {entry.name} is env-only but no settings class reads it")
            entries.setdefault(entry.name, entry)
    emitted = sorted(entries.values(), key=lambda entry: entry.module)
    omitted = sorted(claimed - {name.lower() for name in entries})
    return emitted, omitted


def render(entries: list[EnvName]) -> str:
    """The file text: the header, then one block per module, names in declaration order."""
    width = max((len(entry.name) for entry in entries), default=0) + 1
    lines = list(HEADER)
    module = None
    for entry in entries:
        if entry.module != module:
            module = entry.module
            lines.extend(["", f"# --- {module} ---"])
        lines.append(f"# {f'{entry.name}=':<{width}}    [{entry.source}] {entry.description}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed file differs")
    args = parser.parse_args(argv)
    entries, _ = collect()
    text = render(entries)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"FAIL: {OUTPUT.relative_to(APP_ROOT)} differs from the settings classes; run make env-example")
            return 1
        print(f"OK: {OUTPUT.relative_to(APP_ROOT)} matches the settings classes ({len(entries)} names)")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(APP_ROOT)} ({len(entries)} names)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
